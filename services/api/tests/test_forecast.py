def test_projection_returns_a_row_per_future_date():
    closes, _ = make_garch_series(n=1200)
    today = dt.date(2026, 7, 30)
    targets = [today + dt.timedelta(days=d) for d in (7, 30, 90)]
    out = project_vol_to_dates(closes, targets, today=today)
    assert out["available"]
    assert [r["days"] for r in out["projections"]] == [7, 30, 90]


def test_projection_adds_event_variance_and_it_decays_with_horizon():
    """
    Fixed event variance spread over a longer window contributes less
    annualized volatility -- the 1/T weighting that makes term structures
    invert into an announcement.
    """
    closes, _ = make_garch_series(n=1200)
    today = dt.date(2026, 7, 30)
    event = [today + dt.timedelta(days=3)]
    targets = [today + dt.timedelta(days=d) for d in (7, 60)]

    plain = project_vol_to_dates(closes, targets, today=today)
    withev = project_vol_to_dates(closes, targets, today=today, event_dates=event)

    lift_short = (withev["projections"][0]["projected_vol"]
                  - plain["projections"][0]["projected_vol"])
    lift_long = (withev["projections"][1]["projected_vol"]
                 - plain["projections"][1]["projected_vol"])
    assert lift_short > 0
    assert lift_short > lift_long, "event lift did not decay with horizon"


def test_projection_reports_the_implied_spread_when_given_implied():
    closes, _ = make_garch_series(n=1200)
    today = dt.date(2026, 7, 30)
    out = project_vol_to_dates(closes, [today + dt.timedelta(days=30)],
                               today=today, implied_now=0.40)
    row = out["projections"][0]
    assert row["implied_minus_projected"] == pytest.approx(
        0.40 - row["projected_vol"], abs=1e-6)


def test_projection_degrades_gracefully_without_enough_history():
    out = project_vol_to_dates([100.0] * 30, [dt.date.today() + dt.timedelta(days=30)])
    assert out["available"] is False
    assert "reason" in out
