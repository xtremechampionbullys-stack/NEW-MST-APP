"""
Forecasting tests.

The hard part of testing a forecaster is that you cannot assert it is accurate
-- accuracy depends on the data. What you *can* assert, and what these tests do,
is that it is honest: that its out-of-sample scores are genuinely out of sample,
that it recovers known parameters from synthetic data where the answer is known
by construction, and that it refuses to claim skill it has not demonstrated.
"""

import math

import numpy as np
import pytest

from app.engine.forecast import (
    beta_decompose,
    directional_forecast,
    fit_garch,
    garman_klass_variance,
    har_rv_forecast,
    log_returns,
    project_vol_to_dates,
    propagate_move,
)
from app.providers.base import Bar

import datetime as dt


def make_garch_series(n=1200, omega=2e-6, alpha=0.09, beta=0.88, seed=5):
    """A series with a KNOWN volatility process, so the fit has a right answer."""
    rng = np.random.default_rng(seed)
    var = omega / (1 - alpha - beta)
    price, closes, vars_ = 100.0, [100.0], []
    prev = 0.0
    for _ in range(n):
        var = omega + alpha * prev * prev + beta * var
        r = rng.normal(0, math.sqrt(var))
        prev = r
        price *= math.exp(r)
        closes.append(price)
        vars_.append(var)
    return closes, vars_


def make_bars(closes, day_vols=None, seed=9, steps=200):
    """
    Build OHLC bars whose high/low are the ACTUAL extremes of the price path
    that produced the close. `closes` includes the starting price, so the
    result has one fewer bar than the series has points.

    This matters more than it looks. Garman-Klass is only more efficient than
    squared returns because the range carries information about the path
    between the endpoints. If the fixture draws the high and low from some
    independent distribution -- the obvious lazy way to fake a bar -- then the
    range carries no information about that day's realised variance and the
    estimator has nothing to be efficient about. Testing it against fabricated
    ranges measures the fixture, not the estimator.

    So each session is simulated as a Brownian bridge pinned to the day's known
    log return with that day's known variance, and the high/low are read off
    the path. The open is the previous close, so close-to-close and open-to-
    close returns coincide and both estimators are aiming at the same target.
    """
    rng = np.random.default_rng(seed)
    bars = []
    day = dt.date(2022, 1, 3)
    prev_close = closes[0]
    grid = np.linspace(0.0, 1.0, steps + 1)
    for i, c in enumerate(closes[1:]):
        o = prev_close
        sig = (day_vols[i] if day_vols else 0.01)
        r = math.log(c / o)
        # Standard BM increments over the session, then bridged to land on r.
        inc = rng.normal(0.0, sig / math.sqrt(steps), steps)
        w = np.concatenate(([0.0], np.cumsum(inc)))
        bridge = w - grid * w[-1] + grid * r
        path = o * np.exp(bridge)
        bars.append(Bar(t=dt.datetime.combine(day, dt.time(20, 0), dt.timezone.utc),
                        o=o, h=float(path.max()), l=float(path.min()),
                        c=c, v=1e6))
        prev_close = c
        day += dt.timedelta(days=1)
    return bars


