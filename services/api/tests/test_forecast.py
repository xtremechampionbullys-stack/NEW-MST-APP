def test_garman_klass_is_less_noisy_than_squared_returns():
    """
    The whole reason the range estimator is used. If it were not materially
    more efficient there would be no point carrying OHLC through the pipeline.
    """
    closes, vars_ = make_garch_series(n=1500, seed=11)
    day_vols = [math.sqrt(v) for v in vars_]
    bars = make_bars(closes, day_vols)

    gk = garman_klass_variance(bars)
    rets = log_returns(closes)
    sq = rets ** 2

    truth = np.asarray(vars_[: len(gk)])
    gk_err = float(np.std(gk[: len(truth)] - truth))
    sq_err = float(np.std(sq[: len(truth)] - truth))
    assert gk_err < sq_err, "range estimator was not more efficient than squared returns"


def test_garman_klass_handles_degenerate_bars():
    bars = [Bar(t=dt.datetime.now(dt.timezone.utc), o=0, h=0, l=0, c=0, v=0),
            Bar(t=dt.datetime.now(dt.timezone.utc), o=10, h=11, l=9, c=10.5, v=1)]
    out = garman_klass_variance(bars)
    assert out.shape == (2,)
    assert np.all(np.isfinite(out))


