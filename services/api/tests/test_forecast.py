def test_directional_reports_no_edge_on_a_random_walk():
    """
    The single most important test in this file. A pure random walk has no
    forecastable direction. If the model claims a statistically meaningful edge
    here, it is overfitting and every number it produces is worthless.
    """
    rng = np.random.default_rng(17)
    closes = [100.0]
    for _ in range(1500):
        closes.append(closes[-1] * math.exp(rng.normal(0.0003, 0.015)))

    result = directional_forecast(closes, "RANDOM", horizon_days=21)
    assert result is not None
    assert not result.trustworthy, (
        "model claimed a directional edge on a random walk — it is overfitting")
    assert not result.out_of_sample["statistically_meaningful"]
    assert "no demonstrable directional edge" in result.verdict


def test_directional_edge_is_measured_against_the_base_rate_not_zero():
    """
    Equities drift up, so a model that always says "up" scores well above 50%
    while knowing nothing. The edge must be relative to that, not to a coin.
    """
    rng = np.random.default_rng(23)
    closes = [100.0]
    for _ in range(1500):
        closes.append(closes[-1] * math.exp(rng.normal(0.0012, 0.012)))

    result = directional_forecast(closes, "DRIFT", horizon_days=21)
    assert result.base_rate > 0.55, "test needs a series with real upward drift"
    # Reported accuracy and base rate are rounded to 4dp for display, so the
    # identity is only checkable to that precision -- but it must hold there.
    assert result.edge_vs_base_rate == pytest.approx(
        result.out_of_sample["accuracy"] - result.base_rate, abs=1e-4)
    assert result.out_of_sample["edge"] == pytest.approx(
        result.out_of_sample["accuracy"] - result.out_of_sample["base_rate"],
        abs=2e-4)
    # And it must be the base rate, not 0.5, that the edge is measured from.
    assert result.out_of_sample["edge"] != pytest.approx(
        result.out_of_sample["accuracy"] - 0.5, abs=1e-3)


def test_directional_folds_are_all_out_of_sample():
    closes, _ = make_garch_series(n=1600)
    result = directional_forecast(closes, "X", horizon_days=21, n_folds=4)
    assert result.folds
    for f in result.folds:
        assert f["test_size"] > 0
        assert f["train_size"] > 0
    # Aggregate sample size must equal the sum of the fold test sizes: if it
    # were larger, something in-sample leaked into the score.
    assert result.out_of_sample["samples"] == sum(f["test_size"] for f in result.folds)


def test_directional_needs_a_long_history():
    assert directional_forecast([100.0] * 200, "X") is None


