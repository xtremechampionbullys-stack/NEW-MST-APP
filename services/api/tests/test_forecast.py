def test_har_finds_signal_in_a_series_that_has_one():
    """
    A strongly persistent volatility process is forecastable almost by
    definition. If HAR cannot beat a constant here, it is broken.
    """
    closes, _ = make_garch_series(n=2500, alpha=0.06, beta=0.93, seed=21)
    result = har_rv_forecast(closes, horizon_days=5)
    assert result is not None
    assert result.out_of_sample_r2 is not None
    assert result.out_of_sample_r2 > 0.05, (
        f"HAR found no signal in a highly persistent series "
        f"(OOS R2 {result.out_of_sample_r2:.3f})")


def test_har_reports_no_skill_on_a_constant_volatility_series():
    """
    A series with no volatility clustering has nothing to forecast, and the
    model must say so rather than reporting the level as though it were skill.
    """
    rng = np.random.default_rng(3)
    closes = [100.0]
    for _ in range(1500):
        closes.append(closes[-1] * math.exp(rng.normal(0, 0.012)))
    result = har_rv_forecast(closes, horizon_days=5)
    assert result is not None
    assert result.out_of_sample_r2 < 0.10
    assert "not beating a constant" in result.note or result.out_of_sample_r2 < 0.05


def test_har_coefficients_are_finite_and_forecast_is_positive():
    closes, _ = make_garch_series(n=1200)
    r = har_rv_forecast(closes, horizon_days=5)
    assert r.forecast_vol > 0
    assert all(math.isfinite(v) for v in r.coefficients.values())


def test_har_needs_enough_data():
    assert har_rv_forecast([100.0] * 60) is None


