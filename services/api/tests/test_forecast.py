def test_beta_recovers_a_known_beta():
    rng = np.random.default_rng(31)
    n = 800
    mkt = rng.normal(0.0004, 0.010, n)
    true_beta = 1.6
    idio = rng.normal(0, 0.012, n)
    stock = true_beta * mkt + idio

    bench_closes = 100 * np.exp(np.cumsum(np.insert(mkt, 0, 0)))
    stock_closes = 50 * np.exp(np.cumsum(np.insert(stock, 0, 0)))

    d = beta_decompose(stock_closes.tolist(), bench_closes.tolist(), "S", "B")
    assert d is not None
    assert d.beta == pytest.approx(true_beta, abs=0.12)
    assert 0.3 < d.r_squared < 0.9


def test_variance_decomposition_adds_up():
    """total variance = systematic + idiosyncratic, by construction."""
    rng = np.random.default_rng(37)
    n = 900
    mkt = rng.normal(0, 0.011, n)
    stock = 1.3 * mkt + rng.normal(0, 0.009, n)
    bench_closes = 100 * np.exp(np.cumsum(np.insert(mkt, 0, 0)))
    stock_closes = 80 * np.exp(np.cumsum(np.insert(stock, 0, 0)))

    d = beta_decompose(stock_closes.tolist(), bench_closes.tolist())
    total_var = d.total_vol ** 2
    parts = d.systematic_vol ** 2 + d.idiosyncratic_vol ** 2
    assert parts == pytest.approx(total_var, rel=0.02)


def test_uncorrelated_series_gives_near_zero_beta():
    rng = np.random.default_rng(41)
    a = 100 * np.exp(np.cumsum(rng.normal(0, 0.01, 600)))
    b = 100 * np.exp(np.cumsum(rng.normal(0, 0.01, 600)))
    d = beta_decompose(a.tolist(), b.tolist())
    assert abs(d.beta) < 0.35
    assert d.r_squared < 0.15


def test_propagated_move_band_widens_with_idiosyncratic_risk():
    rng = np.random.default_rng(43)
    n = 800
    mkt = rng.normal(0, 0.010, n)
    bench = 100 * np.exp(np.cumsum(np.insert(mkt, 0, 0)))

    tight = 1.0 * mkt + rng.normal(0, 0.002, n)
    loose = 1.0 * mkt + rng.normal(0, 0.030, n)

    d_tight = beta_decompose((100 * np.exp(np.cumsum(np.insert(tight, 0, 0)))).tolist(),
                             bench.tolist())
    d_loose = beta_decompose((100 * np.exp(np.cumsum(np.insert(loose, 0, 0)))).tolist(),
                             bench.tolist())

    p_tight = propagate_move(d_tight, 0.05)
    p_loose = propagate_move(d_loose, 0.05)
    assert p_loose["idiosyncratic_sd"] > p_tight["idiosyncratic_sd"] * 3
    assert d_loose.r_squared < d_tight.r_squared


