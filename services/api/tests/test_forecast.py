def test_garch_recovers_known_parameters():
    """Fit a series generated by a known GARCH and check the parameters come back."""
    closes, _ = make_garch_series(n=2000, alpha=0.09, beta=0.88)
    fit = fit_garch(closes)
    assert fit is not None
    assert fit.converged
    assert fit.alpha == pytest.approx(0.09, abs=0.06)
    assert fit.beta == pytest.approx(0.88, abs=0.10)
    assert 0.85 < fit.persistence < 0.999


def test_garch_persistence_implies_the_reported_half_life():
    closes, _ = make_garch_series(n=1500)
    fit = fit_garch(closes)
    expected = math.log(0.5) / math.log(fit.persistence)
    assert fit.half_life_days == pytest.approx(expected, rel=1e-6)


def test_garch_projection_mean_reverts_toward_the_long_run_level():
    closes, _ = make_garch_series(n=1500)
    fit = fit_garch(closes)
    path = fit.project(400)
    start_gap = abs(path[0]["daily_vol"] - fit.long_run_vol)
    end_gap = abs(path[-1]["daily_vol"] - fit.long_run_vol)
    assert end_gap < start_gap, "projection did not mean-revert"
    assert end_gap < fit.long_run_vol * 0.15


def test_garch_stays_stationary():
    """alpha + beta >= 1 is a non-stationary fit and must never be returned."""
    for seed in (1, 2, 3, 4):
        closes, _ = make_garch_series(n=800, seed=seed)
        fit = fit_garch(closes)
        assert fit.alpha + fit.beta < 1.0


def test_garch_needs_enough_data():
    assert fit_garch([100.0] * 50) is None


