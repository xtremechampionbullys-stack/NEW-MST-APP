const BASE = process.env.NEXT_PUBLIC_API_URL ?? ''

/**
 * Request bodies are typed from the server's own OpenAPI schema
 * (src/lib/api-schema.d.ts, regenerated by scripts/generate-types.sh), so a
 * field renamed in a Pydantic model breaks the build here rather than at
 * runtime.
 *
 * Response shapes are still declared by hand in types.ts. FastAPI only
 * describes responses that declare a response_model, and most of ours return
 * plain dicts — so rather than pretend, response drift is caught by the
 * contract tests in services/api/tests/test_contracts.py, which assert against
 * what the API actually returns.
 */
type Body<P extends keyof paths, M extends 'post'> =
  paths[P] extends { [K in M]: { requestBody: { content: { 'application/json': infer B } } } }
    ? B
    : never

export type AnalyzeRequestBody = Body<'/api/strategy/analyze', 'post'>
export type BacktestRunBody = Body<'/api/backtest/run', 'post'>
export type DojoRunBody = Body<'/api/dojo/run', 'post'>
export type ForwardSimulateBody = Body<'/api/forward/simulate', 'post'>
export type SaveStrategyBody = Body<'/api/library/strategies', 'post'>

export class ApiError extends Error {
  constructor(message: string, readonly status: number) {
    super(message)
  }
}

async function request<T>(path: string, init?: RequestInit): Promise<T> {
  const res = await fetch(`${BASE}${path}`, {
    ...init,
    headers: { 'Content-Type': 'application/json', ...(init?.headers ?? {}) },
    cache: 'no-store',
  })
  if (!res.ok) {
    let detail = res.statusText
    try {
      const body = await res.json()
      detail = body?.detail ?? detail
    } catch {
      /* non-JSON error body */
    }
    throw new ApiError(typeof detail === 'string' ? detail : JSON.stringify(detail), res.status)
  }
  return res.json() as Promise<T>
}

export interface AnalyzeBody {
  symbol: string
  template?: string | null
  params?: Record<string, unknown>
  legs?: {
    kind: 'call' | 'put' | 'stock'
    quantity: number
    strike?: number | null
    dte?: number
    entry_price?: number | null
    iv?: number | null
  }[]
  spot?: number | null
  american?: boolean
  iv_override?: number | null
  include_monte_carlo?: boolean
  include_surface?: boolean
  measure?: 'risk-neutral' | 'real-world'
  iv_shift?: number
  curve_points?: number
}

